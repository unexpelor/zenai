import fs from "node:fs";
import path from "node:path";
const read = (f) => fs.readFileSync(f, "utf8");
const page = read("app/page.js");
const ai = read("app/api/ai/route.js");
const autopilot = read("app/api/autopilot/route.js");
const marketplace = read("app/api/marketplace/route.js");
const health = read("app/api/health/route.js");
const translate = read("app/api/translate/route.js");
const security = read("lib/api-security.js");
const schema = read("supabase_schema.sql");
const css = read("app/globals.css");
const pkg = JSON.parse(read("package.json"));
const lock = JSON.parse(read("package-lock.json"));
const checks = []; const check=(name,pass)=>checks.push({name,pass:Boolean(pass)});
const routes=fs.readdirSync("app/api",{withFileTypes:true}).filter(d=>d.isDirectory()).map(d=>path.join("app/api",d.name,"route.js"));
check("All API routes require authentication",routes.every(f=>read(f).includes("requireApiUser")));
check("All API routes are rate limited",[ai,autopilot,marketplace,translate,health].every(x=>x.includes("rateLimit")));
check("AI timeouts",ai.includes("AbortSignal.timeout(30000)"));
check("Marketplace timeouts",marketplace.includes("AbortSignal.timeout(7000)")&&marketplace.includes("AbortSignal.timeout(30000)"));
check("Autopilot JSON validation",autopilot.includes("validateAutopilotResult"));
check("No unsafe HTML injection",!page.includes("dangerouslySetInnerHTML")&&!page.includes("innerHTML"));
check("RLS enabled",schema.includes("enable row level security"));
check("RLS user isolation",schema.includes("auth.uid() = user_id"));
check("Provider secrets not public",!page.includes("NEXT_PUBLIC_GROQ")&&!page.includes("NEXT_PUBLIC_OPENROUTER")&&!page.includes("NEXT_PUBLIC_GEMINI")&&!page.includes("NEXT_PUBLIC_TAVILY"));
check("Supabase lock aligned",lock.packages?.["node_modules/@supabase/supabase-js"]?.version==="2.57.4");
check("deepl-node unused dependency removed",!pkg.dependencies?.["deepl-node"]&&!lock.packages?.["node_modules/deepl-node"]);
check("Global locale trigger",page.includes("[locale, canonicalRevision]")&&page.includes("Object.keys(aiCanonicalRef.current)"));
check("AI stale-result protection",page.includes("aiRequestSeqRef")&&page.includes("isLatestAiRequest"));
check("Translation stale-request protection",page.includes("translationRequestRef.current.controller?.abort()"));
check("Translation cache uses source hash + locale",page.includes("sourceHash")&&read("lib/localization/localizationCache.js").includes("${sourceHash}_${locale}"));
check("Persisted state normalization",page.includes("normalizeDiagnosis")&&page.includes("normalizeAutopilot")&&page.includes("safeArray"));
check("Cloud tab whitelist",page.includes("validTabs.has(saved.tab)"));
check("Health not-configured semantics",health.includes("not_configured"));
check("Market blocks zero-evidence AI",marketplace.includes("uniqueSources.length === 0"));
check("Reduced motion",css.includes("prefers-reduced-motion"));
check("Mobile input sizing",css.includes("max-width: 640px")&&css.includes("font-size: 16px"));
for(const x of checks)console.log(`${x.pass?"PASS":"FAIL"} - ${x.name}`);
const failed=checks.filter(x=>!x.pass); console.log(`RESULT: ${checks.length-failed.length}/${checks.length} final audit checks passed`); if(failed.length)process.exitCode=1;
